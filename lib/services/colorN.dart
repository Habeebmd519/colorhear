  List<String>? getColorName(int red, int green, int blue) {
    int max = 255 * 255 * 3; // maximum possible squared distance
    int min;
    List<String>? name;

    for (var color in colorList) {
      int r = int.parse(color[1]);
      int g = int.parse(color[2]);
      int b = int.parse(color[3]);
      min =
          ((red - r) * (red - r) +
              (green - g) * (green - g) +
              (blue - b) * (blue - b)) ~/
          3;
      if (min < max) {
        max = min;
        name = color;
      }
    }
    return name;
  }

  String getClosestColorName(int r, int g, int b) {
    double minDistance = double.infinity;
    String closestColor = "Unknown";

    for (var color in colorList) {
      int cr = int.parse(color[1]);
      int cg = int.parse(color[2]);
      int cb = int.parse(color[3]);
      double dist =
          ((r - cr) * (r - cr) + (g - cg) * (g - cg) + (b - cb) * (b - cb))
              .toDouble();

      if (dist < minDistance) {
        minDistance = dist;
        closestColor = color[0];
      }
    }

    return closestColor;
  }
